/// A strip-like grid with shared edges, a far jump and a restart, over 300 vertices.
fn grid_indices() -> Vec<u32> {
    let mut out = Vec::new();
    for y in 0..10u32 {
        for x in 0..14u32 {
            let i = y * 15 + x;
            out.extend([i, i + 1, i + 15, i + 15, i + 1, i + 16]);
        }
    }
    out.extend([299, 7, 150, 0, 1, 2]);
    out
}

/// Each triangle starting at its smallest index: the codec keeps winding, not the first vertex.
fn canonical(indices: &[u32]) -> Vec<[u32; 3]> {
    indices.chunks(3).map(|t| (0..3).map(|r| [t[r], t[(r + 1) % 3], t[(r + 2) % 3]]).min().unwrap()).collect()
}

#[test]
fn index_buffers_round_trip() {
    for indices in [grid_indices(), INDEX_BUFFER.to_vec(), vec![5, 9, 70000, 70000, 9, 3]] {
        let encoded = encode_index_buffer(&indices);
        assert_eq!(canonical(&decode_index_buffer(&encoded, indices.len()).unwrap()), canonical(&indices));
        assert_eq!(decode_index_sequence(&encode_index_sequence(&indices), indices.len()).unwrap(), indices);
    }
}

#[test]
fn vertex_buffers_round_trip_across_blocks() {
    // 40-byte vertices: blocks of 192, so 500 vertices span three blocks.
    let vertices: Vec<u8> = (0..500u32 * 10).flat_map(|i| (i.wrapping_mul(2_654_435_761) >> (i % 7 * 4)).to_le_bytes()).collect();
    let smooth: Vec<u8> = (0..500u32 * 10).flat_map(|i| (i / 10 * 3 + i % 10).to_le_bytes()).collect();
    for version in [0, 1] {
        for v in [&vertices, &smooth] {
            let encoded = encode_vertex_buffer(v, 40, version);
            assert_eq!(&decode_vertex_buffer(&encoded, 500, 40).unwrap(), v);
        }
    }
}

#[test]
fn rejects_corrupt_streams() {
    assert_eq!(decode_index_buffer(&INDEX_DATA_V0[..20], 12), Err(Error::Size));
    assert_eq!(decode_index_buffer(&[0xe5; 30], 3), Err(Error::Header(0xe5)));
    assert!(decode_vertex_buffer(&VERTEX_DATA_V0[..40], 4, 12).is_err());
    assert_eq!(decode_vertex_buffer(&VERTEX_DATA_V0, 4, 10), Err(Error::Shape));
}
