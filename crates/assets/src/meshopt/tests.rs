/// Four 12-byte vertices: u16 position xyz, two u8 normal bytes, u16 uv.
fn vertex_buffer() -> Vec<u8> {
    let pv = |p: [u16; 3], t: [u16; 2]| p.iter().flat_map(|v| v.to_le_bytes()).chain([0, 0]).chain(t.iter().flat_map(|v| v.to_le_bytes())).collect::<Vec<u8>>();
    [pv([0, 0, 0], [0, 0]), pv([300, 0, 0], [500, 0]), pv([0, 300, 0], [0, 500]), pv([300, 300, 0], [500, 500])].concat()
}

