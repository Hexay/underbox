#!/usr/bin/env python3
"""Pairs each Box2D struct's fields in abi (managed's layout) with box2d-sys (C's layout) by offset
and writes crates/engine2/src/physics2d/layout_tests.rs, which asserts the two layouts agree.

Rerun after bumping third_party/box2d or regenerating abi. Exits non-zero, writing nothing, when a
field has no C counterpart at its offset or the names disagree: then the Box2D pin is wrong.
usage: python3 tools/box2d_layout.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ABI = ROOT / "crates/abi/src/generated/structs.rs"
SYS = ROOT / "crates/box2d-sys/src/bindings.rs"
OUT = ROOT / "crates/engine2/src/physics2d/layout_tests.rs"

# Managed flattens C arrays into numbered fields (v0..v7, colorCount0..23): those sit inside a C array.
FLATTENED = re.compile(r"^(.*?)(\d+)$")


def parse(text, offset_re, size_re):
    fields, sizes = {}, {}
    for s, f, o in re.findall(offset_re, text):
        fields.setdefault(s, []).append((f, int(o)))
    for s, n in re.findall(size_re, text):
        sizes[s] = int(n)
    return fields, sizes


def norm(name):
    return name.replace("_", "").lower()


def main():
    abi_fields, abi_sizes = parse(
        ABI.read_text(),
        r"offset_of!\((b2\w+), (\w+)\) == (\d+)\)",
        r"size_of::<(b2\w+)>\(\) == (\d+)\)",
    )
    sys_fields, sys_sizes = parse(
        SYS.read_text(),
        r"offset_of!\((b2\w+), (\w+)\) - (\d+)usize\]",
        r"\[\"Size of (b2\w+)\"\]\[::std::mem::size_of::<b2\w+>\(\) - (\d+)usize\]",
    )
    lines, errors = [], []
    for name in sorted(abi_sizes):
        if name not in sys_sizes:
            errors.append(f"{name}: not in box2d-sys")
            continue
        by_offset = {o: f for f, o in sys_fields.get(name, [])}
        pairs = []
        for f, o in abi_fields.get(name, []):
            c = by_offset.get(o)
            base = FLATTENED.match(f)
            if c is not None and (norm(c) == norm(f) or (base and norm(c).startswith(norm(base.group(1))[:3]))):
                pairs.append(f"{f} = {c}")
            elif c is None and base:
                continue
            elif norm(f) in ("basedef",) and c == "base":
                pairs.append(f"{f} = {c}")
            else:
                errors.append(f"{name}.{f} @{o}: C has {c!r}")
        lines.append(f"    same_layout!({name}: {', '.join(pairs)});")
    if errors:
        sys.exit("layout mismatch:\n  " + "\n  ".join(errors))
    OUT.write_text(
        "//! Generated by tools/box2d_layout.py: managed's Box2D structs (abi) match C's (box2d-sys).\n\n"
        "use super::layout::same_layout;\n\n#[test]\nfn abi_structs_match_box2d() {\n"
        + "\n".join(lines)
        + "\n}\n"
    )
    print(f"wrote {OUT.relative_to(ROOT)}: {len(lines)} structs")


main()
