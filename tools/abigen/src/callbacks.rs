//! `generated/callbacks.rs`: safe Rust functions for every managed function native may call.

use crate::names;
use crate::structs::Structs;
use crate::types::{self, Conv, Dir};
use abi_spec::Abi;
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;

pub fn emit(abi: &Abi, structs: &Structs) -> Result<String, String> {
    let mut out = String::from(HEADER);
    writeln!(out, "use crate::generated::slots::{{class, handle}};\nuse crate::generated::structs::*;\nuse crate::rt::callbacks::callback;\nuse crate::rt::types::*;\nuse std::ffi::{{CStr, c_char, c_void}};\n").unwrap();

    let mut by_class: BTreeMap<&str, Vec<_>> = BTreeMap::new();
    for cb in &abi.callbacks {
        by_class.entry(cb.class.managed.as_str()).or_default().push(cb);
    }
    for (class, cbs) in by_class {
        writeln!(out, "/// managed `{class}`\npub mod {} {{\n    use super::*;\n", names::module(&names::type_name(class))).unwrap();
        let mut used = BTreeSet::new();
        for cb in cbs {
            let ctx = |e: String| format!("callback {} ({}): {e}", cb.index, cb.name);
            let mut fname = names::ident(&cb.member);
            while !used.insert(fname.clone()) {
                fname.push('_');
            }
            let mut params = Vec::new();
            let mut abi_tys = Vec::new();
            let mut call = Vec::new();
            let mut param_names = BTreeSet::new();
            for a in &cb.args {
                let m = types::map(a, false, Dir::Callback, None, structs).map_err(ctx)?;
                let mut id = names::ident(&a.name);
                while !param_names.insert(id.clone()) {
                    id.push('_');
                }
                let safe = if m.conv == Conv::ByVal { format!("&{}", m.safe) } else { m.safe.clone() };
                params.push(format!("{id}: {safe}"));
                abi_tys.push(m.abi.clone());
                call.push(match m.conv {
                    Conv::Same => id,
                    Conv::Bool => format!("{id} as {}", m.abi),
                    Conv::CStrIn => format!("{id}.map_or(std::ptr::null(), CStr::as_ptr)"),
                    Conv::NativeRef => format!("{id}.as_raw()"),
                    Conv::RawPtr => format!("{id}.as_ptr()"),
                    Conv::ByVal => format!("{id} as *const _"),
                    Conv::OutRef => format!("{id} as *mut _"),
                    Conv::StrOut => return Err(ctx("string-return conversion on an argument".into())),
                    Conv::Slice(_) | Conv::Len => return Err(ctx("buffers fold only on slots".into())),
                });
            }
            let r = types::map(&cb.ret, true, Dir::Callback, None, structs).map_err(ctx)?;
            let (ret_abi, ret_safe) = if r.abi == "()" { (String::new(), String::new()) } else { (format!(" -> {}", r.abi), format!(" -> {}", r.safe)) };
            let wrap: String = match r.conv {
                Conv::Same => "r".into(),
                Conv::Bool => "r != 0".into(),
                Conv::StrOut => "unsafe { crate::rt::types::cstr_arg(r) }.map(|s| s.to_string_lossy().into_owned())".into(),
                Conv::NativeRef => "NativeRef::from_raw(r)".into(),
                Conv::RawPtr => "RawPtr::from_raw(r)".into(),
                other => return Err(ctx(format!("can't return {other:?}"))),
            };
            writeln!(
                out,
                "    /// `{}` (callback {})\n    pub fn {fname}({}){ret_safe} {{\n        // SAFETY: managed's table holds this export's [UnmanagedCallersOnly] thunk at this index, with this signature.\n        let f: unsafe extern \"C\" fn({}){ret_abi} = unsafe {{ callback({}) }};\n        let r = unsafe {{ f({}) }};\n        {wrap}\n    }}\n",
                cb.name,
                cb.index,
                params.join(", "),
                abi_tys.join(", "),
                cb.index,
                call.join(", ")
            )
            .unwrap();
        }
        writeln!(out, "}}\n").unwrap();
    }
    Ok(out)
}

const HEADER: &str = "// @generated by tools/abigen from abi/engine.json. Do not edit.\n#![allow(non_camel_case_types, unused_imports, unused_variables, clippy::all)]\n\n";
