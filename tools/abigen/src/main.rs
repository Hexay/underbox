//! abigen: abi/engine.json + abi/layouts.json → crates/abi/src/generated/ and crates/tap/src/generated/.
//! usage: abigen <abi dir> <abi out dir> <tap out dir>

mod buffers;
mod callbacks;
mod fields;
mod names;
mod slots;
mod structs;
mod tap;
mod types;

use std::path::{Path, PathBuf};
use std::process::ExitCode;

fn main() -> ExitCode {
    let args: Vec<PathBuf> = std::env::args_os().skip(1).map(PathBuf::from).collect();
    let [abi_dir, out_dir, tap_dir] = args.as_slice() else {
        eprintln!("usage: abigen <abi dir> <abi out dir> <tap out dir>");
        return ExitCode::from(2);
    };
    match run(abi_dir, out_dir, tap_dir) {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("abigen: {e}");
            ExitCode::FAILURE
        }
    }
}

fn run(abi_dir: &Path, out_dir: &Path, tap_dir: &Path) -> Result<(), String> {
    let abi = abi_spec::load_abi(&abi_dir.join("engine.json"))?;
    let layouts = abi_spec::load_layouts(&abi_dir.join("layouts.json"))?;
    let structs = structs::Structs::new(&layouts);

    let planned = slots::plan(&abi, &structs)?;
    let emitted = slots::emit(&abi, &structs, &planned)?;
    let files = [
        ("structs.rs", structs.emit()?),
        ("slots.rs", emitted.slots),
        ("thunks.rs", emitted.thunks),
        ("callbacks.rs", callbacks::emit(&abi, &structs)?),
        ("mod.rs", MOD_RS.into()),
    ];
    let mut paths = write(out_dir, &files)?;
    paths.extend(write(tap_dir, &tap::emit(&abi, &structs, &planned)?)?);
    let fmt = std::process::Command::new("rustfmt").args(["--edition", "2024"]).args(&paths).status();
    if !fmt.is_ok_and(|s| s.success()) {
        eprintln!("abigen: rustfmt unavailable or failed; output left unformatted");
    }

    println!(
        "abigen: hash {}, {} slots, {} callbacks, {} layouts → {}, {}",
        abi.hash,
        abi.slots.len(),
        abi.callbacks.len(),
        layouts.len(),
        out_dir.display(),
        tap_dir.display()
    );
    Ok(())
}

fn write(dir: &Path, files: &[(&str, String)]) -> Result<Vec<PathBuf>, String> {
    std::fs::create_dir_all(dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    files
        .iter()
        .map(|(name, text)| {
            let path = dir.join(name);
            std::fs::write(&path, text).map_err(|e| format!("{}: {e}", path.display()))?;
            Ok(path)
        })
        .collect()
}

const MOD_RS: &str = "// @generated by tools/abigen. Do not edit.\npub mod callbacks;\npub mod slots;\npub mod structs;\npub(crate) mod thunks;\n";
