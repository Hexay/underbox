//! abigen: abi/engine.json + abi/layouts.json → crates/abi/src/generated/.
//! usage: abigen <abi dir> <out dir>

mod callbacks;
mod names;
mod slots;
mod structs;
mod types;

use std::path::{Path, PathBuf};
use std::process::ExitCode;

fn main() -> ExitCode {
    let args: Vec<PathBuf> = std::env::args_os().skip(1).map(PathBuf::from).collect();
    let [abi_dir, out_dir] = args.as_slice() else {
        eprintln!("usage: abigen <abi dir> <out dir>");
        return ExitCode::from(2);
    };
    match run(abi_dir, out_dir) {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("abigen: {e}");
            ExitCode::FAILURE
        }
    }
}

fn run(abi_dir: &Path, out_dir: &Path) -> Result<(), String> {
    let abi = abi_spec::load_abi(&abi_dir.join("engine.json"))?;
    let layouts = abi_spec::load_layouts(&abi_dir.join("layouts.json"))?;
    let structs = structs::Structs::new(&layouts);

    let emitted = slots::emit(&abi, &structs)?;
    let files = [
        ("structs.rs", structs.emit()?),
        ("slots.rs", emitted.slots),
        ("thunks.rs", emitted.thunks),
        ("callbacks.rs", callbacks::emit(&abi, &structs)?),
        ("mod.rs", MOD_RS.into()),
    ];

    std::fs::create_dir_all(out_dir).map_err(|e| format!("{}: {e}", out_dir.display()))?;
    for (name, text) in &files {
        let path = out_dir.join(name);
        std::fs::write(&path, text).map_err(|e| format!("{}: {e}", path.display()))?;
    }
    let paths: Vec<_> = files.iter().map(|(n, _)| out_dir.join(n)).collect();
    let fmt = std::process::Command::new("rustfmt").args(["--edition", "2024"]).args(&paths).status();
    if !fmt.is_ok_and(|s| s.success()) {
        eprintln!("abigen: rustfmt unavailable or failed; output left unformatted");
    }

    println!(
        "abigen: hash {}, {} slots, {} callbacks, {} layouts → {}",
        abi.hash,
        abi.slots.len(),
        abi.callbacks.len(),
        layouts.len(),
        out_dir.display()
    );
    Ok(())
}

const MOD_RS: &str = "// @generated by tools/abigen. Do not edit.\npub mod callbacks;\npub mod slots;\npub mod structs;\npub(crate) mod thunks;\n";
